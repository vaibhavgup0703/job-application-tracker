// Runs BEFORE `ng build` on Vercel. It writes the live API address into environment.ts.
//
// WHY: Angular is compiled into static files, so the API URL must be baked in at BUILD time.
// Real-life example: printing the shop's phone number on a flyer. It has to be right before printing.
//
// Vercel provides API_URL as an environment variable (Project Settings -> Environment Variables),
// e.g. https://jobtracker-api.onrender.com
// Locally you don't run this script, so environment.ts keeps pointing to http://localhost:5000.

import { writeFileSync } from 'node:fs';

const apiBase = (process.env.API_URL ?? '').trim().replace(/\/+$/, ''); // drop trailing slashes

if (!apiBase) {
  console.error('set-env: API_URL is not set. Add it in Vercel -> Settings -> Environment Variables.');
  process.exit(1); // fail the build loudly instead of shipping a frontend that calls localhost
}

const content = `// GENERATED by scripts/set-env.mjs during the build. Do not commit this version.
export const environment = {
  apiUrl: '${apiBase}/api',
};
`;

writeFileSync(new URL('../src/environments/environment.ts', import.meta.url), content);
console.log(`set-env: apiUrl = ${apiBase}/api`);
